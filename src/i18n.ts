export const money = (cents: number, lang: Lang) =>
  new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB", {
    style: "currency",
    currency: "EUR",
  }).format(cents / 100);
export const formatDate = (date: string, lang: Lang) =>
  new Intl.DateTimeFormat(lang === "it" ? "it-IT" : "en-GB", {
    timeZone: "UTC",
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(new Date(date + "T12:00Z"));
